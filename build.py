#!/usr/bin/env python3
"""Build THE SURVIVAL GAME: compile survival.c to WebAssembly with zig cc
(a clang that targets wasm32-freestanding), gzip+base64 it into the JS
shell, and emit single-file HTML builds (standalone + LAN server copy).
Also cross-compiles the Windows .exe when zig is available."""
import gzip, base64, pathlib, subprocess, sys, shutil, os

HERE = pathlib.Path(__file__).parent
SRC = HERE / "src"
OUT = pathlib.Path.home() / "workspace" / "your_files"
ZIG = os.environ.get("TSG_ZIG", str(pathlib.Path.home() / "workspace" / "tools" / "zig-x86_64-linux-0.14.1" / "zig"))

def run(cmd):
    print("+", " ".join(cmd))
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout); print(r.stderr); sys.exit(1)

def main():
    wasm = SRC / "survival.wasm"
    run([ZIG, "cc", "-target", "wasm32-freestanding", "-DPLAT_WASM", "-O2",
         "-std=c99", "-nostdlib", "-Wl,--no-entry", "-Wl,--export=frame",
         "-Wl,--export-memory", "-Wl,--initial-memory=16777216",
         "-o", str(wasm), str(SRC / "survival.c")])
    gz = gzip.compress(wasm.read_bytes(), compresslevel=9, mtime=0)
    shell = (SRC / "shell.html").read_text()
    html = shell.replace("__WASM64__", base64.b64encode(gz).decode())
    dest = OUT / "the-survival-game.html"
    dest.write_text(html)
    srv = OUT / "survival-game-server"
    srv.mkdir(parents=True, exist_ok=True)
    (srv / "index.html").write_text(html)
    shutil.copy(HERE / "server.js", srv / "server.js")
    print(f"html {len(html)} bytes (wasm {wasm.stat().st_size} raw / {len(gz)} gz) -> {dest}")
    # embed the web build into the native binaries: the app serves this
    # exact page to browser guests from its built-in web server
    hb = html.encode()
    arr = ",".join(str(b) for b in hb)
    (SRC / "webbuild.h").write_text(
        "// generated by build.py: the web build, embedded for the native\n"
        "// builds' built-in web server (friends play from a browser)\n"
        f"static const unsigned char TSG_WEB_HTML[] = {{{arr}}};\n"
        f"static const unsigned TSG_WEB_HTML_LEN = {len(hb)};\n")
    print(f"webbuild.h {len(hb)} bytes embedded")
    # Windows .exe (cross-compiled, single file). The .rc (icon, version
    # info, manifest) is compiled with zig rc and linked in, so the exe
    # carries an identity instead of being an anonymous unsigned blob.
    exe = OUT / "TheSurvivalGame.exe"
    res = SRC / "winres" / "survival.res"
    r = subprocess.run([ZIG, "rc", "/fo", str(res), "survival.rc"],
                       cwd=SRC / "winres", capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout); print(r.stderr); sys.exit(1)
    run([ZIG, "cc", "-target", "x86_64-windows-gnu", "-DPLAT_WIN32", "-O2",
         "-std=c99", "-Wl,--subsystem,windows",
         "-o", str(exe), str(SRC / "survival.c"), str(res),
         "-lgdi32", "-lwinmm", "-lws2_32", "-lshell32"])
    print(f"exe {exe.stat().st_size} bytes -> {exe}")
    # Linux binary (X11 + ALSA) — built with the system compiler: zig's
    # bundled libc headers don't see the host's X11/ALSA dev files.
    lin = OUT / "TheSurvivalGame-linux"
    syscc = shutil.which("cc") or shutil.which("gcc")
    if syscc:
        run([syscc, "-DPLAT_LINUX", "-O2", "-std=gnu99",
             "-o", str(lin), str(SRC / "survival.c"),
             "-lX11", "-lasound", "-lm", "-lpthread"])
    else:
        print("no system C compiler found; skipping the Linux build")
    print(f"linux {lin.stat().st_size} bytes -> {lin}")
    # macOS binary (Apple Silicon; pure-C Cocoa host, no SDK headers —
    # framework symbols resolve at runtime via dynamic lookup)
    mac = OUT / "TheSurvivalGame-mac"
    run([ZIG, "cc", "-target", "aarch64-macos.11.0-none", "-DPLAT_MAC", "-O2",
         "-std=gnu99", "-o", str(mac), str(SRC / "survival.c"), str(SRC / "mac_main.c"),
         "-Wl,-undefined,dynamic_lookup", "-lm"])
    print(f"mac {mac.stat().st_size} bytes -> {mac}")
    # package the Mac binary as a proper .app bundle in a zip (the bare
    # Mach-O is a miserable download: no icon, no bundle identity, and
    # Finder doesn't treat it as an app). The binary stays ad-hoc signed
    # by zig, so Gatekeeper still needs a right-click -> Open on first
    # launch until there's a Developer ID + notarization.
    import struct as _struct
    appdir = OUT / ".app-stage" / "TheSurvivalGame.app" / "Contents"
    shutil.rmtree(OUT / ".app-stage", ignore_errors=True)
    (appdir / "MacOS").mkdir(parents=True)
    (appdir / "Resources").mkdir(parents=True)
    shutil.copy(mac, appdir / "MacOS" / "TheSurvivalGame")
    shutil.copy(SRC / "macapp" / "Info.plist", appdir / "Info.plist")
    png = (SRC / "macapp" / "app-icon-512.png").read_bytes()
    icns = b"icns" + _struct.pack(">I", 8 + 8 + len(png)) + b"ic09" + _struct.pack(">I", 8 + len(png)) + png
    (appdir / "Resources" / "AppIcon.icns").write_bytes(icns)
    maczip = shutil.make_archive(str(OUT / "TheSurvivalGame-mac"), "zip",
                                 OUT / ".app-stage", "TheSurvivalGame.app")
    shutil.rmtree(OUT / ".app-stage", ignore_errors=True)
    print(f"mac app zip {pathlib.Path(maczip).stat().st_size} bytes -> {maczip}")
    # source bundle for handing over
    bundle = OUT / "survival-game-source"
    bundle.mkdir(parents=True, exist_ok=True)
    for f in ["shell.html"]:
        shutil.copy(SRC / f, bundle / f)
    for p in sorted(SRC.glob("*.c")):   # unity build: survival.c + every piece file + mac_main.c
        shutil.copy(p, bundle / p.name)
    for f in ["build.py", "build.bat", "server.js", "README.md"]:
        if (HERE / f).exists(): shutil.copy(HERE / f, bundle / f)
    print("source bundle ->", bundle)
    # Android APK (WebView wrapper around the standalone HTML), when the
    # SDK under ~/workspace/tools is present; skipped silently otherwise.
    apk_script = HERE / "android" / "build_apk.sh"
    sdk_bt = pathlib.Path.home() / "workspace" / "tools" / "android-sdk" / "build-tools" / "34.0.0" / "aapt2"
    if apk_script.exists() and sdk_bt.exists():
        r = subprocess.run(["bash", str(apk_script)], capture_output=True, text=True)
        tail = (r.stdout + r.stderr).strip().splitlines()
        print("apk:", tail[-1] if tail else f"exit {r.returncode}")
    else:
        print("apk: skipped (Android SDK not installed)")

if __name__ == "__main__":
    main()
